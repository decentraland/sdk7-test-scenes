// Prepare the compact Node-only authoring folder. CI checks it against these exact sources.
// Usage: node scripts/htn-authoring.mjs [--check]
import { build, version } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = fileURLToPath(new URL('../', import.meta.url))
const check = process.argv.length === 3 && process.argv[2] === '--check'
if (process.argv.length > 2 && !check) {
  console.error('Usage: node scripts/htn-authoring.mjs [--check]')
  process.exitCode = 2
} else {
  try {
    if (version !== '0.18.20') throw new Error(`Compact authoring generation requires esbuild 0.18.20; found ${version}. Install the scene dev dependencies.`)
    const bundled = await build({
      absWorkingDir: root,
      entryPoints: ['tools/htn/cli.ts'],
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: 'node20',
      tsconfigRaw: { compilerOptions: { alwaysStrict: true, useDefineForClassFields: false } },
      write: false,
      logLevel: 'warning',
      banner: { js: '// Generated by scripts/htn-authoring.mjs; edit tools/htn sources, not this file.' }
    })
    const noticeSource = await readFile(path.join(root, 'scripts/htn-notices.mjs'), 'utf8')
    const noticeRoot = "const root = new URL('../', import.meta.url)"
    if (!noticeSource.includes(noticeRoot)) throw new Error('Notice source root changed; update compact authoring generation.')
    const files = new Map([
      ['compiler.cjs', bundled.outputFiles[0].contents],
      ['notices.mjs', Buffer.from('// Generated by scripts/htn-authoring.mjs from scripts/htn-notices.mjs.\n' + noticeSource.replace(noticeRoot, "const root = new URL('../../', import.meta.url)"))],
      ['LICENSE', await readFile(path.join(root, 'tools/htn/LICENSE'))],
      ['LICENSE.htn_planner', await readFile(path.join(root, 'tools/htn/LICENSE.htn_planner'))]
    ])
    const directory = path.join(root, 'tools/htn-authoring')
    if (!check) await mkdir(directory, { recursive: true })
    for (const [name, contents] of files) {
      const file = path.join(directory, name)
      if (check) {
        const actual = await readFile(file).catch(error => {
          if (error.code === 'ENOENT') throw new Error(`Missing tools/htn-authoring/${name}: run npm run htn:authoring`)
          throw error
        })
        // Git may normalize text line endings on checkout; the generated content is otherwise exact.
        if (actual.toString().replace(/\r\n/g, '\n') !== Buffer.from(contents).toString().replace(/\r\n/g, '\n')) {
          throw new Error(`Stale tools/htn-authoring/${name}: run npm run htn:authoring`)
        }
      } else await writeFile(file, contents)
    }
    console.log(check ? 'Compact HTN authoring files match their sources.' : 'Prepared tools/htn-authoring (compiler, notices and licences).')
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
