// Derive the deployable notice from the source licences and example credits.
import { readFile, writeFile } from 'node:fs/promises'
import * as fs from 'node:fs/promises'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const output = new URL('htn-notices.txt', root)
const check = process.argv.length === 3 && process.argv[2] === '--check'

async function main() {
  if (process.argv.length > 2 && !check) throw new Error('Usage: node scripts/htn-notices.mjs [--check]')
  const license = await readFile(new URL('src/htn-planner/LICENSE.htn_planner', root), 'utf8')
  const sections = [
    'HTN planner: upstream licence and example notices.\nGenerated by npm run htn:notices; edit the source notice files instead.',
    'Upstream htn_planner (MIT), ported from commit aec08fa:\nhttps://github.com/urosidoki/htn_planner/tree/aec08fa\n\n' + license.trim(),
    'Original TypeScript port contributions (MIT):\n\n' + (await readFile(new URL('src/htn-planner/LICENSE', root), 'utf8')).trim()
  ]
  try {
    sections.push((await readFile(new URL('src/examples/canon/THIRD_PARTY_NOTICES.md', root), 'utf8')).trim())
  } catch (error) {
    if (error.code !== 'ENOENT') throw error // A consumer may copy the library without the example set.
  }
  const expected = sections.join('\n\n' + '='.repeat(72) + '\n\n').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '') + '\n'
  if (check) {
    const actual = await readFile(output, 'utf8')
    if (actual.replace(/\r\n/g, '\n') !== expected) throw new Error('Stale htn-notices.txt: run npm run htn:notices')
    const require = createRequire(import.meta.url)
    const { getPublishableFiles } = require('@dcl/sdk-commands/dist/logic/project-files')
    const files = await getPublishableFiles({ fs }, fileURLToPath(root))
    if (!files.some((path) => path.replace(/\\/g, '/') === 'htn-notices.txt')) {
      throw new Error('htn-notices.txt is excluded from the SDK publishable file list; update .dclignore')
    }
    console.log('HTN notices match their sources and are included in the SDK publishable file list.')
  } else {
    await writeFile(output, expected)
    console.log('Updated htn-notices.txt')
  }
}

main().catch((error) => {
  console.error(error.message)
  process.exitCode = 1
})
