// Every committed generated module (`*.htn.ts`, `*.facts.ts` under src/, and the frozen reference domains' under
// test/fixtures/reference) matches what its source compiles to today.
// Upstream regenerates its example domains in the build (premake5.lua:219-242), so they never go stale; ours are
// committed, so this test recompiles each one from the `// Source:` line of its header (with the export name and
// import specifier it already has) and names the command that regenerates a stale one.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import * as fs from 'node:fs'
import * as nodePath from 'node:path'
import { compileDomainFile, emitDomainModule, emitWorldStateModule, formatDiagnostic, parseWorldState } from '../../../tools/htn/compiler'
import { WorldState } from '../../../src/htn-planner/htn/world-state'
import { FIXTURES, REPO_ROOT } from './helpers'

const GENERATED_BY = '// Generated by tools/htn (npm run htn:compile). Do not edit by hand.'
/** Written by scripts/htn-examples.mjs and scripts/htn-lab.ts: regenerated all at once. */
const EXAMPLES_DIR = 'src/examples/upstream/generated/'

const slashes = (path: string) => path.split(nodePath.sep).join('/')
const lf = (text: string) => text.replace(/\r\n/g, '\n')

function findGenerated(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const path = nodePath.join(dir, entry.name)
    if (entry.isDirectory()) return findGenerated(path)
    if (!/\.(htn|facts)\.ts$/.test(entry.name)) return []
    return fs.readFileSync(path, 'utf8').startsWith(GENERATED_BY) ? [path] : []
  })
}

interface Header {
  lines: string[] // header comment lines after GENERATED_BY, without `// `
  source: string // repo-relative
  exportName: string
  importPath: string
}

function readHeader(text: string): Header | string {
  const lines = lf(text).split('\n')
  const header: string[] = []
  for (let i = 1; i < lines.length && lines[i].startsWith('// '); i++) header.push(lines[i].slice(3))
  const source = /^Source: (\S+)/.exec(header[0] ?? '')?.[1]
  const exportName = /^export const (\w+): (?:DomainIR|WorldFacts) = /m.exec(text)?.[1]
  const importPath = /^import type \{ (?:DomainIR|WorldFacts) \} from '([^']+)'/m.exec(text)?.[1]
  if (!source || !exportName || !importPath) return 'no `// Source:` line, export or import in its header'
  return { lines: header, source, exportName, importPath }
}

/** The import specifier `npm run htn:compile` computes for `out` (tools/htn/cli.ts importSpecifier). */
function defaultImport(out: string, module: string): string {
  const spec = slashes(nodePath.relative(nodePath.dirname(out), nodePath.join(REPO_ROOT, 'src', 'htn-planner', 'htn', module)))
  return spec.startsWith('.') ? spec : './' + spec
}

function regenerateCommand(file: string, h: Header): string {
  const rel = slashes(nodePath.relative(REPO_ROOT, file))
  if (rel.startsWith(EXAMPLES_DIR)) return 'npm run htn:examples'
  const module = h.source.endsWith('.worldstate') ? 'world-state' : 'ir'
  const irImport = h.importPath === defaultImport(file, module) ? '' : ` --ir-import ${h.importPath}`
  return `npm run htn:compile -- ${h.source} ${rel} ${h.exportName}${irImport}`
}

/**
 * What the module's source compiles to. A hot reload revision (header `... with @REVISION@ replaced` / `by A`) is
 * compiled as scripts/htn-lab.ts hotReload() does: the token replaced, includes read from the fixture
 * Domains/Includes.
 */
function recompile(h: Header): string {
  const source = nodePath.join(REPO_ROOT, h.source)
  const options = { irImportPath: h.importPath, header: h.lines }
  if (h.source.endsWith('.worldstate')) {
    const world = new WorldState()
    parseWorldState(fs.readFileSync(source, 'utf8'), world)
    return emitWorldStateModule(world, h.exportName, options)
  }
  const revision = /with @REVISION@ replaced$/.test(h.lines[0]) ? /^by (\w+)$/.exec(h.lines[1] ?? '')?.[1] : undefined
  const readFile = revision
    ? (path: string) =>
        nodePath.resolve(path) === nodePath.resolve(source)
          ? fs.readFileSync(source, 'utf8').split('@REVISION@').join(revision)
          : fs.readFileSync(nodePath.join(FIXTURES, 'Domains', 'Includes', nodePath.basename(path)), 'utf8')
    : undefined
  const result = compileDomainFile(source, { readFile })
  if (!result.ok) throw new Error(result.diagnostics.map(formatDiagnostic).join('\n'))
  return emitDomainModule(result.ir, h.exportName, options)
}

/** Null when `file` (or `text`, its content) matches its source; otherwise why, and the command that fixes it. */
function staleness(file: string, text = fs.readFileSync(file, 'utf8')): string | null {
  const rel = slashes(nodePath.relative(REPO_ROOT, file))
  const h = readHeader(text)
  if (typeof h === 'string') return `${rel}: ${h}`
  if (!fs.existsSync(nodePath.join(REPO_ROOT, h.source))) return `${rel}: its source ${h.source} does not exist`
  let expected: string
  try {
    expected = lf(recompile(h))
  } catch (e) {
    return `${rel}: ${h.source} does not compile:\n${(e as Error).message}`
  }
  const actual = lf(text)
  if (actual === expected) return null
  const a = actual.split('\n')
  const b = expected.split('\n')
  let line = 0
  while (line < a.length && a[line] === b[line]) line++
  return (
    `${rel} is stale: it differs from what ${h.source} compiles to, from line ${line + 1}\n` +
    `  committed: ${a[line] ?? '<end of file>'}\n  compiled:  ${b[line] ?? '<end of file>'}\n` +
    `  regenerate: ${regenerateCommand(file, h)}`
  )
}

const files = [...findGenerated(nodePath.join(REPO_ROOT, 'src')), ...findGenerated(nodePath.join(REPO_ROOT, 'test', 'fixtures', 'reference'))]

test('every generated module under src/ and test/fixtures/reference matches its source', () => {
  assert.ok(files.length >= 70, `found ${files.length} generated modules`)
  const stale = files.map(f => staleness(f)).filter((s): s is string => s !== null)
  assert.deepEqual(stale, [], '\n' + stale.join('\n\n'))
})

test('a stale module is reported with the command that regenerates it', () => {
  const pick = (part: string) => files.find(f => slashes(f).includes(part))!
  const hello = pick('src/examples/basics/hello.htn.ts')
  const edited = fs.readFileSync(hello, 'utf8').replace("name: 'Hello'", "name: 'Hullo'")
  const report = staleness(hello, edited)
  assert.ok(report, 'edited module reported')
  assert.match(report, /src\/examples\/basics\/hello\.htn\.ts is stale: .* src\/examples\/basics\/hello\.domain/)
  assert.match(report, /regenerate: npm run htn:compile -- src\/examples\/basics\/hello\.domain src\/examples\/basics\/hello\.htn\.ts helloDomain$/)

  const facts = pick('generated/human.facts.ts')
  assert.match(staleness(facts, fs.readFileSync(facts, 'utf8') + '// extra\n')!, /regenerate: npm run htn:examples$/)
  const rev = pick('hot-reload/WandererRevB.htn.ts')
  assert.equal(staleness(rev), null, 'hot reload revisions recompile with their @REVISION@')
})
