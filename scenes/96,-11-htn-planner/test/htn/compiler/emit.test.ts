// emitDomainModule output: exact round trip, typechecks under the scene tsconfig; CLI behavior.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import * as fs from 'node:fs'
import * as nodePath from 'node:path'
import { compileDomainFile, emitDomainModule, emitWorldStateModule, parseWorldState } from '../../../tools/htn/compiler'
import { addFacts, WorldFacts, WorldState } from '../../../src/htn-planner/htn/world-state'
import type { DomainIR } from '../../../src/htn-planner/htn/ir'
import { FIXTURES, REPO_ROOT, compile, describe as show } from './helpers'

const domainsDir = nodePath.join(FIXTURES, 'Domains')
const roots = [
  ...fs.readdirSync(domainsDir).filter(f => f.endsWith('.domain')),
  ...fs.readdirSync(nodePath.join(domainsDir, 'Test')).map(f => 'Test/' + f)
].map(f => nodePath.join(domainsDir, f))

function compileOk(path: string): DomainIR {
  const result = compileDomainFile(path)
  assert.ok(result.ok, show(result))
  return result.ir
}

/** Evaluates the object literal of an emitted module. */
function evaluate(moduleText: string): unknown {
  const marker = ': DomainIR = '
  const literal = moduleText.slice(moduleText.indexOf(marker) + marker.length)
  return new Function(`return (${literal})`)()
}

test('emitted module evaluates to exactly the IR (including -0)', () => {
  const ir = compile('(:domain Root top_level_domain (:method (run) top_level_method (b () ((!v -0.0 0.1 "q\\x" "it\'s\nmulti-line" (a (1 -2)))))))')
  assert.ok(ir.ok, show(ir))
  const text = emitDomainModule(ir.ir, 'rootDomain')
  assert.match(text, /^\/\/ Generated by tools\/htn/)
  assert.match(text, /\nimport type \{ DomainIR \} from '\.\.\/htn\/ir'\n/)
  assert.match(text, /\nexport const rootDomain: DomainIR = \{/)
  assert.deepStrictEqual(evaluate(text), ir.ir)
  for (const path of roots) {
    const domain = compileOk(path)
    assert.deepStrictEqual(evaluate(emitDomainModule(domain, 'x')), domain, path)
  }
})

test('emitDomainModule: custom import path and invalid export names', () => {
  const domain = compileOk(nodePath.join(domainsDir, 'Wanderer.domain'))
  assert.match(emitDomainModule(domain, 'w', { irImportPath: '../../htn/ir' }), /from '\.\.\/\.\.\/htn\/ir'/)
  assert.throws(() => emitDomainModule(domain, 'not-valid'), /invalid export name/)
})

test('every emitted fixture module typechecks under the scene tsconfig', { timeout: 120000 }, () => {
  const dir = nodePath.join(REPO_ROOT, '.test-build', 'htn-emit')
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
  const files: string[] = []
  for (const path of roots) {
    const name = nodePath.basename(path, '.domain').replace(/[^A-Za-z0-9_]/g, '_')
    const file = `${name}.ts`
    fs.writeFileSync(
      nodePath.join(dir, file),
      emitDomainModule(compileOk(path), `${name}Domain`, { irImportPath: '../../src/htn-planner/htn/ir' })
    )
    files.push(file)
  }
  // Extends the scene tsconfig (ES2020 lib, strict, @dcl/js-runtime types), only for these files.
  fs.writeFileSync(
    nodePath.join(dir, 'tsconfig.json'),
    JSON.stringify({ extends: '../../tsconfig.json', compilerOptions: { noEmit: true }, include: [], files })
  )
  const tsc = nodePath.join(REPO_ROOT, 'node_modules', 'typescript', 'bin', 'tsc')
  const result = spawnSync(process.execPath, [tsc, '-p', nodePath.join(dir, 'tsconfig.json')], { encoding: 'utf8' })
  assert.equal(result.status, 0, `${result.stdout}\n${result.stderr}`)
})

test('CLI: writes a module with a computed import path; reports located errors with a non-zero exit', { timeout: 120000 }, () => {
  const dir = nodePath.join(REPO_ROOT, '.test-build', 'htn-cli', 'src', 'generated')
  fs.rmSync(nodePath.join(REPO_ROOT, '.test-build', 'htn-cli'), { recursive: true, force: true })
  const script = nodePath.join(REPO_ROOT, 'scripts', 'htn-compile.mjs')
  const out = nodePath.join(dir, 'wanderer.ts')
  const ok = spawnSync(process.execPath, [script, nodePath.join(domainsDir, 'Wanderer.domain'), out], {
    encoding: 'utf8',
    cwd: REPO_ROOT
  })
  assert.equal(ok.status, 0, ok.stderr)
  const text = fs.readFileSync(out, 'utf8')
  assert.match(text, /\/\/ Source: test\/htn\/fixtures\/upstream\/Domains\/Wanderer\.domain/)
  assert.match(text, /import type \{ DomainIR \} from '\.\.\/\.\.\/\.\.\/\.\.\/src\/htn-planner\/htn\/ir'/)
  assert.match(text, /export const wandererDomain: DomainIR = /)

  const bad = spawnSync(
    process.execPath,
    [script, nodePath.join(FIXTURES, 'HTNDiagnosticTests', 'DiagnosticSemanticErrors.domain'), nodePath.join(dir, 'bad.ts'), 'bad'],
    { encoding: 'utf8', cwd: REPO_ROOT }
  )
  assert.equal(bad.status, 1)
  const lines = bad.stderr.trim().split(/\r?\n/)
  assert.match(lines[0], /DiagnosticSemanticErrors\.domain:6:26-6:41: error unknown-variable: Unknown variable 'missing_target'/)
  assert.equal(lines.filter(l => /:\d+:\d+-\d+:\d+: error [a-z-]+: /.test(l)).length, 3)
  assert.equal(fs.existsSync(nodePath.join(dir, 'bad.ts')), false)

  const usage = spawnSync(process.execPath, [script], { encoding: 'utf8', cwd: REPO_ROOT })
  assert.equal(usage.status, 2)
  assert.match(usage.stderr, /usage: npm run htn:compile/)
})

test('emitWorldStateModule: the module round-trips through addFacts to the same rows', () => {
  const path = nodePath.join(FIXTURES, 'WorldStates', 'Wanderer.worldstate')
  const world = new WorldState()
  parseWorldState(fs.readFileSync(path, 'utf8'), world)
  const text = emitWorldStateModule(world, 'wandererFacts', { irImportPath: '../htn/world-state' })
  assert.match(text, /import type \{ WorldFacts \} from '\.\.\/htn\/world-state'/)
  const body = text.slice(text.indexOf('= ') + 2)
  const facts = new Function(`return ${body}`)() as WorldFacts
  const copy = new WorldState()
  addFacts(copy, facts)
  assert.deepEqual(copy.tableKeys(), world.tableKeys())
  for (const k of world.tableKeys()) {
    const slash = k.lastIndexOf('/')
    assert.deepEqual(copy.rows(k.slice(0, slash), Number(k.slice(slash + 1))), world.rows(k.slice(0, slash), Number(k.slice(slash + 1))))
  }
})

